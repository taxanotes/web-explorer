#!/usr/bin/env bash
#
# Creates (or brings up to date) a Taxanotes instance on a hosting server
# laid out by Rob's provision-site toolkit (/var/www/<category>/<domain>/
# {releases/<version>/code, deployment_environments/live, settings, backups}).
# The production counterpart of scripts/new-instance.sh: the same instance
# definition, the same recipes and migrations, one checkout per instance on
# web/sites/default (instances/README.md, "Environments").
#
#   scripts/hosting/new-instance.sh <slug> <version> [--tarball FILE | --git URL [--ref REF]]
#                                   [--category NN] [--reinstall]
#
# runs ON the server as the site owner (rob, sudo without password) and, step
# by step and only where something is missing:
#   release    releases/<version>/code from a `git archive` tarball (--tarball;
#              the repo has no remote the server can reach yet) or through the
#              toolkit's create_release (--git/--ref); then the symlinks the
#              toolkit expects (settings.local.php -> settings/1, files ->
#              the live assets, drush -> vendor/bin/drush), permissions,
#              composer install --no-dev
#   site       create_site_structure when /var/www/<category>/<domain> is
#              missing, plus the private/tmp asset directories and logs/
#   secrets    settings/instance.env (keys of instances/.env.example; created
#              with a random hash salt, database passwords and
#              SITE_MAIL=noreply@<domain>; a placeholder address is warned about)
#   database   d<slug>_1 and user u<slug>_1 (the toolkit's naming, as
#              create_database would, but through `sudo mariadb`: the toolkit
#              command is interactive and wants a MySQL root password); a
#              read-only user on the Scratchpads source s_<slug> when that
#              database exists (scripts/hosting/load-source-db.sh loads it)
#   settings   settings/1/settings.local.php generated by
#              scripts/lib/instance.php for the production environment, plus
#              the hosting block (file paths, READ COMMITTED), and
#              settings/1/settings.migrate.php with the `migrate` connection
#   web        the Apache vhost (HTTP -> HTTPS, basic auth on the whole site,
#              HSTS, install.php denied) when missing, a self-signed
#              certificate until certbot replaces it, the htpasswd file with
#              one user <slug> and a random password printed once, certbot
#   drupal     drush site:install only into an EMPTY database, the themes,
#              recipes/taxanotes_front with the instance inputs, the logo
#              (settings/assets/logo.png, outside git), the eleven Scratchpads
#              migrations (the files and images only when instance.env
#              SOURCE_FILES_DIR names the D7 files directory), cache rebuild
#   live       `deploy <domain> live <version>` (backup, composer, docroot
#              symlink flip, php-fpm reload, updb, cr) when live does not
#              point at this release yet; the drush cron crontab line
#
# Re-running it changes nothing that is already in place (the recipe creates
# blocks and views only when missing and re-seeds the site texts; the
# migrations import only rows that changed in Drupal 7). It never installs
# over tables: a database with tables that does not bootstrap or whose
# install never finished stops the run; --reinstall takes a backup_db dump
# and installs again (site:install drops the tables). A hand-written
# settings.local.php is replaced only with --reinstall (a .bak copy is kept).
#
# Needs on the server: bash 4, sudo, mariadb, php, composer, apache2 with
# ssl/rewrite/headers, htpasswd (apache2-utils), certbot, openssl, and the
# toolkit commands on PATH: create_site_structure, create_release (--git),
# backup_db, deploy.
set -euo pipefail

usage() {
  cat >&2 <<EOF
usage: $0 <slug> <version> [--tarball FILE | --git URL [--ref REF]] [--category NN] [--reinstall]
  <slug>       instances/<slug>/instance.yml in the shipped code
  <version>    release name, releases/<version>/code (e.g. 0.2.0)
  --tarball F  git archive of the code (prefix code/) to extract as the release
  --git URL    repository for the toolkit's create_release (with --ref REF)
  --category   /var/www/<category> (default 09)
  --reinstall  backup_db, then drop the instance's tables and install again
EOF
  exit 2
}

log() { printf '\n==> %s\n' "$*"; }
note() { printf '    %s\n' "$*"; }
warn() { printf '    WARNING: %s\n' "$*" >&2; }
die() { printf 'new-instance: %s\n' "$*" >&2; exit 1; }

slug=""
version=""
tarball=""
git_url=""
git_ref=""
category=09
reinstall=0
while [ $# -gt 0 ]; do
  case "$1" in
    --tarball) [ $# -ge 2 ] || usage; tarball="$2"; shift 2 ;;
    --git) [ $# -ge 2 ] || usage; git_url="$2"; shift 2 ;;
    --ref) [ $# -ge 2 ] || usage; git_ref="$2"; shift 2 ;;
    --category) [ $# -ge 2 ] || usage; category="$2"; shift 2 ;;
    --reinstall) reinstall=1; shift ;;
    -*) usage ;;
    *)
      if [ -z "$slug" ]; then slug="$1"; elif [ -z "$version" ]; then version="$1"; else usage; fi
      shift ;;
  esac
done
[ -n "$slug" ] && [ -n "$version" ] || usage
[ -z "$tarball" ] || [ -z "$git_url" ] || die "--tarball and --git exclude each other"
[[ "$slug" =~ ^[a-z][a-z0-9_]*$ ]] || die "slug '$slug' must be lowercase letters, digits and underscores"
[[ "$version" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || die "version '$version' has characters a directory name should not"
[[ "$category" =~ ^[0-9]{2}$ ]] || die "category '$category' must be two digits"
[ "$(id -un)" != "root" ] || die "run as the site owner (rob), not root"
for cmd in sudo mariadb php composer htpasswd certbot openssl tar create_site_structure backup_db deploy; do
  command -v "$cmd" > /dev/null || die "$cmd is not on PATH"
done
environment=production
# Everything the script, tar and composer create is group-readable for
# www-data and closed to others, whatever umask the caller had (a run under
# `umask 077` once left web/ unreadable to Apache: HTTP 500 on every page).
umask 027
owner="$(id -un)"
group=www-data
stamp="$(date +%Y%m%d_%H%M%S)"
php_memory=1024M

# Random alphanumerics (passwords in SQL and htpasswd need no quoting then).
random_string() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | cut -c1-"$1"; }

# One value from the instance.env ('' when unset).
env_get() { sed -n "s/^$1=//p" "$env_file" | tail -n 1 | sed -e "s/^['\"]//" -e "s/['\"]\$//"; }

# ---------------------------------------------------------------------------
# The domain is hostnames.production[0] of instance.yml, which lives in the
# code being shipped. Before the release exists (vendor/ and the YAML parser
# with it) the one key is read with awk; instance.php confirms it later.
yml_production_host() {
  awk '
    /^[^ #]/ { top = $1 }
    top == "hostnames:" && /^  [a-z]+:/ { env = $1 }
    top == "hostnames:" && env == "production:" && /^    - / { sub(/^    - */, ""); gsub(/["'"'"']/, ""); print; exit }
  ' "$1"
}
log "Instance $slug, release $version"
yml_rel="instances/$slug/instance.yml"
if [ -n "$tarball" ]; then
  [ -f "$tarball" ] || die "$tarball does not exist"
  domain="$(tar -xzOf "$tarball" "code/$yml_rel" 2> /dev/null | yml_production_host /dev/stdin)" || true
  [ -n "$domain" ] || die "$tarball holds no code/$yml_rel with hostnames.production"
else
  # Any release of any Taxanotes site on this server ships the same file.
  found="$(find /var/www -mindepth 6 -maxdepth 6 -path "/var/www/*/*/releases/*/code/instances" -type d 2> /dev/null | head -n 1)"
  [ -n "$found" ] && [ -f "$found/$slug/instance.yml" ] || die "no release on this server holds $yml_rel: ship a tarball (--tarball)"
  domain="$(yml_production_host "$found/$slug/instance.yml")"
  [ -n "$domain" ] || die "$found/$slug/instance.yml has no hostnames.production"
fi
[[ "$domain" =~ ^[a-z0-9.-]+$ ]] || die "hostname '$domain' is not a plain domain name"
base="/var/www/$category/$domain"
code="$base/releases/$version/code"
live="$base/deployment_environments/live"
docroot="$live/docroot"
settings_dir="$base/settings"
env_file="$settings_dir/instance.env"
url="https://$domain"
note "domain: $domain"
note "site base: $base"
note "release code: $code"

# ---------------------------------------------------------------------------
log "Site structure: $base"
if [ -d "$base" ]; then
  note "exists (create_site_structure is not re-run: it would reset the modes of every release)"
else
  create_site_structure "$category" "$domain"
fi
for d in "$live/assets/private" "$live/assets/tmp" "$base/logs" "$settings_dir/1"; do
  [ -d "$d" ] || mkdir -p "$d"
done
chmod 770 "$live/assets/private" "$live/assets/tmp"
chgrp "$group" "$live/assets/private" "$live/assets/tmp"
note "assets: public/files, private, tmp (770 $owner:$group); logs/"

# ---------------------------------------------------------------------------
log "Release: $code"
if [ -d "$code" ]; then
  note "exists, kept"
elif [ -n "$tarball" ]; then
  mkdir -p "$base/releases/$version"
  tar -xzf "$tarball" -C "$base/releases/$version"
  [ -d "$code/web" ] || die "$tarball did not produce code/web (expected a git archive with --prefix=code/)"
  note "extracted $tarball"
elif [ -n "$git_url" ]; then
  create_release "$domain" "$version" "$git_url" "$git_ref"
else
  die "release $version does not exist: pass --tarball FILE or --git URL [--ref REF]"
fi
[ -f "$code/$yml_rel" ] || die "$code/$yml_rel does not exist in the release"
site_dir="$code/web/sites/default"
# The toolkit's layout: settings and files live outside the release.
ln -sfn ../../../../../../settings/1/settings.local.php "$site_dir/settings.local.php"
ln -sfn ../../../../../../deployment_environments/live/assets/public/files "$site_dir/files"
# Drush 13 runs through Composer's vendor/bin/drush proxy only (the repo's
# vendor/drush/drush/drush link looks for drush.php beside itself); the
# toolkit's deploy and drush_run call ./drush.
ln -sfn vendor/bin/drush "$code/drush"
note "symlinks: settings.local.php -> settings/1, files -> live assets, drush -> vendor/bin/drush"
if [ ! -f "$code/vendor/autoload.php" ]; then
  chown -R "$owner:$group" "$base/releases/$version"
  find "$base/releases/$version" -type d -exec chmod 750 {} +
  find "$base/releases/$version" -type f -exec chmod 640 {} +
  find "$code/scripts" -type f -name '*.sh' -exec chmod 750 {} +
  [ ! -f "$code/tools/dev/phpcomposer/composer.phar" ] || chmod 750 "$code/tools/dev/phpcomposer/composer.phar"
  note "permissions: $owner:$group, directories 750, files 640"
fi
( cd "$code" && composer install --no-dev --optimize-autoloader --no-interaction --no-progress 2>&1 | tail -n 3 )
[ -f "$code/vendor/drush/drush/drush.php" ] || die "composer install left no vendor/drush/drush/drush.php"
note "composer install --no-dev done"

# Drush on this release and site: drush.php (what the vendor/bin/drush shell
# launcher execs) run with a PHP memory limit the revision import needs; the
# cwd is the code directory so vendor/ resolves, --uri gives the site its name.
drush() {
  ( cd "$code" && php -d memory_limit="$php_memory" vendor/drush/drush/drush.php --uri="$url" "$@" )
}
# One value (or list, one item per line) from instance.yml for this
# environment, defaults applied (scripts/lib/instance.php knows them).
inst() { php "$code/scripts/lib/instance.php" get "$code/$yml_rel" "$1" "$environment"; }

# ---------------------------------------------------------------------------
log "Instance definition: $code/$yml_rel"
confirmed="$(inst hostnames.production | head -n 1)"
[ "$confirmed" = "$domain" ] || die "instance.php reads hostnames.production[0] as '$confirmed', the bootstrap read '$domain'"
site_name="$(inst site.name)"
site_slogan="$(inst site.slogan)"
front_title="$(inst site.front_title)"
front_intro="$(inst site.front_intro)"
about_body="$(inst site.about_body)"
footer_text="$(inst site.footer_text)"
theme="$(inst site.theme)"
admin_theme="$(inst site.admin_theme)"
subdir="$(inst drupal.sites_subdir)"
profile="$(inst drupal.profile)"
db_name="$(inst drupal.database)"
source_db="$(inst source.database)"
source_vocabulary="$(inst source.vocabulary)"
[ -n "$site_name" ] || die "site.name is missing in $yml_rel"
[ -n "$profile" ] && [ -n "$db_name" ] || die "instance.php returned no drupal.profile/database for $yml_rel"
[ "$db_name" = "d${slug}_1" ] || die "drupal.database for $environment is '$db_name'; this layout expects d${slug}_1 (toolkit database 1 of the site)"
[ -z "$source_db" ] || [ "$source_db" = "s_${slug}" ] || die "source.database for $environment is '$source_db'; this layout expects s_${slug}"
note "site: $site_name"
note "database: $db_name; Scratchpads source: ${source_db:-none}; profile: $profile; themes: $theme / $admin_theme"
note "(web/sites/$subdir in the ddev multisite; one checkout per instance here, always sites/default)"

# ---------------------------------------------------------------------------
log "Secrets: $env_file"
db_user="u${slug}_1"
migrate_user="s_${slug}_ro"
if [ ! -f "$env_file" ]; then
  sed -e "s/^HASH_SALT=.*/HASH_SALT=$(openssl rand -hex 32)/" \
    -e "s/^DB_HOST=.*/DB_HOST=localhost/" \
    -e "s/^DB_USER=.*/DB_USER=$db_user/" \
    -e "s/^DB_PASSWORD=.*/DB_PASSWORD=$(random_string 24)/" \
    -e "s/^MIGRATE_DB_HOST=.*/MIGRATE_DB_HOST=localhost/" \
    -e "s/^MIGRATE_DB_USER=.*/MIGRATE_DB_USER=$migrate_user/" \
    -e "s/^MIGRATE_DB_PASSWORD=.*/MIGRATE_DB_PASSWORD=$(random_string 24)/" \
    -e "s|^SITE_MAIL=.*|SITE_MAIL=noreply@$domain|" \
    "$code/instances/.env.example" > "$env_file"
  note "created from instances/.env.example with a fresh HASH_SALT, random database passwords and SITE_MAIL=noreply@$domain"
else
  note "exists, kept"
fi
chmod 600 "$env_file"
[ -n "$(env_get HASH_SALT)" ] || die "HASH_SALT is empty in $env_file"
db_host="$(env_get DB_HOST)"
db_host="${db_host:-localhost}"
db_user="$(env_get DB_USER)"
db_user="${db_user:-u${slug}_1}"
db_pass="$(env_get DB_PASSWORD)"
migrate_user="$(env_get MIGRATE_DB_USER)"
migrate_pass="$(env_get MIGRATE_DB_PASSWORD)"
site_mail="$(env_get SITE_MAIL)"
site_mail="${site_mail:-noreply@$domain}"
case "$site_mail" in
  *@example.com|*@example.org|*@example.net)
    warn "SITE_MAIL=$site_mail in $env_file is a placeholder: receivers reject mail from example domains; set an address at $domain (or one a mailer can send from)" ;;
esac
admin_pass="$(env_get ADMIN_PASSWORD)"
# The Scratchpads public files directory on this server (the deploy step
# rsyncs the referenced subset there, scripts/list-source-files.php lists
# it): instance.env SOURCE_FILES_DIR, else instance.yml
# source.files.production. Empty: the attachments and images are skipped.
source_files_dir="$(env_get SOURCE_FILES_DIR)"
[ -n "$source_files_dir" ] || source_files_dir="$(inst source.files)"
[ -z "$source_files_dir" ] || [ -d "$source_files_dir" ] || warn "SOURCE_FILES_DIR $source_files_dir does not exist on this server: every attachment and image will be skipped"
[ -n "$db_pass" ] || die "DB_PASSWORD is empty in $env_file"
for v in "$db_user" "$db_pass" "$migrate_user" "$migrate_pass"; do
  case "$v" in *"'"*|*"\\"*) die "a database credential in $env_file contains a quote or backslash; use letters, digits and punctuation" ;; esac
done

# ---------------------------------------------------------------------------
log "Database: $db_name, user $db_user@localhost (sudo mariadb)"
[ "$db_host" = "localhost" ] || die "DB_HOST is '$db_host': this script manages a database on this server only"
sudo mariadb -e "CREATE DATABASE IF NOT EXISTS \`$db_name\` CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
CREATE USER IF NOT EXISTS '$db_user'@'localhost' IDENTIFIED BY '$db_pass';
ALTER USER '$db_user'@'localhost' IDENTIFIED BY '$db_pass';
GRANT ALL PRIVILEGES ON \`$db_name\`.* TO '$db_user'@'localhost';
FLUSH PRIVILEGES;"
note "exists (created if it was missing); $db_user's password follows $env_file"
table_count="$(sudo mariadb -N -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '$db_name'" | tr -dc '0-9')"
[ -n "$table_count" ] || die "could not count the tables of $db_name"
note "$table_count tables"
source_ready=0
if [ -n "$source_db" ] && [ -n "$migrate_user" ]; then
  source_tables="$(sudo mariadb -N -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '$source_db'" | tr -dc '0-9')"
  if [ "${source_tables:-0}" -gt 0 ]; then
    [ -n "$migrate_pass" ] || die "MIGRATE_DB_PASSWORD is empty in $env_file"
    sudo mariadb -e "CREATE USER IF NOT EXISTS '$migrate_user'@'localhost' IDENTIFIED BY '$migrate_pass';
ALTER USER '$migrate_user'@'localhost' IDENTIFIED BY '$migrate_pass';
REVOKE ALL PRIVILEGES, GRANT OPTION FROM '$migrate_user'@'localhost';
GRANT SELECT ON \`$source_db\`.* TO '$migrate_user'@'localhost';
FLUSH PRIVILEGES;"
    note "Scratchpads source $source_db: $source_tables tables; $migrate_user@localhost has SELECT only"
    source_ready=1
  else
    note "Scratchpads source $source_db is not loaded (scripts/hosting/load-source-db.sh $slug <dump>): migrations will be skipped"
  fi
else
  note "no Scratchpads source for this instance"
fi

# ---------------------------------------------------------------------------
log "Settings: $settings_dir/1/settings.local.php (+ settings.migrate.php)"
marker='Generated by scripts/new-instance.sh'
hosting_block() {
  cat <<EOF

// Hosting additions by scripts/hosting/new-instance.sh (toolkit layout).
// The toolkit's backup_db/restore_db read the credentials of this file with
// grep and expect each key once, so this block names none of the connection
// keys and the Scratchpads connection sits in settings.migrate.php.
\$databases['default']['default']['init_commands'] = [
  'isolation_level' => 'SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED',
];
\$settings['file_public_path'] = 'sites/default/files';
\$settings['file_private_path'] = '$live/assets/private';
\$settings['file_temp_path'] = '$live/assets/tmp';
// The toolkit owns the modes ($owner:$group, directories 750, files 640);
// Drupal's own hardening of sites/default is off so this file can be
// regenerated by the script.
\$settings['skip_permissions_hardening'] = TRUE;
\$config['system.logging']['error_level'] = 'hide';
\$config['system.performance']['css']['preprocess'] = TRUE;
\$config['system.performance']['js']['preprocess'] = TRUE;
EOF
}
tmp_local="$(mktemp)"
tmp_migrate="$(mktemp)"
php "$code/scripts/lib/instance.php" settings-local "$code/$yml_rel" "$env_file" "$environment" settings.migrate.php > "$tmp_local"
hosting_block >> "$tmp_local"
php "$code/scripts/lib/instance.php" settings-migrate "$code/$yml_rel" "$env_file" "$environment" > "$tmp_migrate"
local_php="$settings_dir/1/settings.local.php"
migrate_php="$settings_dir/1/settings.migrate.php"
install_file() {
  # install_file <generated> <target>: replaces the target when it differs.
  if [ -f "$2" ] && cmp -s "$1" "$2"; then
    note "$(basename "$2") unchanged"
    rm -f "$1"
  else
    [ ! -f "$2" ] || chmod u+w "$2"
    mv "$1" "$2"
    chown "$owner:$group" "$2"
    chmod 640 "$2"
    note "$(basename "$2") written (640 $owner:$group)"
  fi
}
if [ -f "$local_php" ] && ! grep -q "$marker" "$local_php"; then
  if [ "$reinstall" -eq 1 ]; then
    cp -p "$local_php" "$local_php.bak-$stamp"
    chmod 600 "$local_php.bak-$stamp"
    note "settings.local.php was not generated by this script: copied to settings.local.php.bak-$stamp (--reinstall replaces it)"
  else
    rm -f "$tmp_local" "$tmp_migrate"
    die "$local_php exists and was not generated by this script: put its hash salt and database password into $env_file and run with --reinstall, which replaces it (a .bak copy is kept)"
  fi
fi
install_file "$tmp_local" "$local_php"
if [ -s "$tmp_migrate" ]; then
  install_file "$tmp_migrate" "$migrate_php"
else
  rm -f "$tmp_migrate"
  [ ! -f "$migrate_php" ] || { rm -f "$migrate_php"; note "settings.migrate.php removed (no Scratchpads source)"; }
fi

# ---------------------------------------------------------------------------
log "Basic auth: $settings_dir/htpasswd"
htpasswd_file="$settings_dir/htpasswd"
if [ -f "$htpasswd_file" ]; then
  note "exists, kept (users: $(cut -d: -f1 "$htpasswd_file" | paste -sd ' ' -))"
else
  basic_pass="$(random_string 20)"
  htpasswd -cbB "$htpasswd_file" "$slug" "$basic_pass" > /dev/null
  chown "$owner:$group" "$htpasswd_file"
  chmod 640 "$htpasswd_file"
  note "created with user $slug; its password, shown this once: $basic_pass"
  note "add a reviewer: htpasswd -B $htpasswd_file <name>"
fi

# ---------------------------------------------------------------------------
log "Apache: /etc/apache2/sites-available/$domain.conf"
vhost="/etc/apache2/sites-available/$domain.conf"
le_dir="/etc/letsencrypt/live/$domain"
if [ -f "$vhost" ]; then
  note "exists, kept (the script never rewrites a vhost; edit it by hand)"
else
  if sudo test -f "$le_dir/fullchain.pem"; then
    cert_lines="    SSLCertificateFile $le_dir/fullchain.pem
    SSLCertificateKeyFile $le_dir/privkey.pem
    Include /etc/letsencrypt/options-ssl-apache.conf"
    note "certificate: Let's Encrypt ($le_dir)"
  else
    sudo mkdir -p /etc/apache2/ssl
    if ! sudo test -f "/etc/apache2/ssl/$domain.key"; then
      sudo openssl req -x509 -nodes -days 1095 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 \
        -subj "/CN=$domain" -addext "subjectAltName=DNS:$domain" -addext "basicConstraints=CA:FALSE" \
        -keyout "/etc/apache2/ssl/$domain.key" -out "/etc/apache2/ssl/$domain.crt" 2> /dev/null
      sudo chmod 600 "/etc/apache2/ssl/$domain.key"
    fi
    cert_lines="    SSLCertificateFile /etc/apache2/ssl/$domain.crt
    SSLCertificateKeyFile /etc/apache2/ssl/$domain.key"
    note "certificate: self-signed until certbot replaces it (below)"
  fi
  auth_name="$(printf '%s' "$site_name" | tr -d '"') preview (taxanotes)"
  sudo tee "$vhost" > /dev/null <<EOF
# $domain on $(hostname) - Taxanotes instance "$slug" (Drupal 11), live environment.
# Written $(date -u +%Y-%m-%dT%H:%MZ) by scripts/hosting/new-instance.sh, which never
# rewrites it: edit by hand. Toolkit layout: the docroot is a symlink that deploy
# flips between releases/<version>/code/web. certbot --apache replaces the
# certificate lines when it issues the Let's Encrypt certificate.

<VirtualHost *:80>
    ServerName $domain
    ServerAdmin webmaster@localhost
    ErrorLog \${APACHE_LOG_DIR}/${domain}_error.log
    CustomLog \${APACHE_LOG_DIR}/${domain}_access.log combined

    # Everything to HTTPS.
    RewriteEngine On
    RewriteCond %{HTTPS} !=on
    RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]
</VirtualHost>

<VirtualHost *:443>
    ServerName $domain
    ServerAdmin webmaster@localhost
    DocumentRoot $docroot

    ErrorLog \${APACHE_LOG_DIR}/${domain}_error.log
    CustomLog \${APACHE_LOG_DIR}/${domain}_access.log combined

    SSLEngine on
    SSLProtocol all -SSLv3 -TLSv1 -TLSv1.1
$cert_lines

    # HSTS: one year, no preload, no subdomains.
    Header always set Strict-Transport-Security "max-age=31536000"

    # The installer and the cache-rebuild script are not used on a deployed
    # site (drush instead); update.php stays, update_free_access is FALSE.
    <LocationMatch "^/core/(install|rebuild)\.php$">
        Require all denied
    </LocationMatch>

    <Directory "$docroot">
        Options FollowSymLinks
        AllowOverride All

        # Privacy gate for the whole site while the pilot is reviewed.
        # Only "Require valid-user" here: adding "Require all granted" alongside
        # it would OR the two and switch the gate off.
        AuthType Basic
        AuthName "$auth_name"
        AuthUserFile $htpasswd_file
        Require valid-user
    </Directory>
</VirtualHost>
EOF
  sudo a2ensite "$domain.conf" > /dev/null
  if ! sudo apachectl -t > /dev/null 2>&1; then
    sudo apachectl -t || true
    die "Apache rejects the configuration with $vhost: fix it, then re-run"
  fi
  sudo systemctl reload apache2
  note "written, enabled, Apache reloaded"
fi
if sudo test -f "$le_dir/fullchain.pem"; then
  note "Let's Encrypt certificate present ($le_dir), renewed by certbot's timer"
else
  note "requesting a Let's Encrypt certificate (DNS for $domain must point at this server)"
  if sudo certbot --apache -d "$domain" --non-interactive --agree-tos --no-eff-email 2>&1 | tail -n 5; then
    sudo systemctl reload apache2
    note "certificate issued; the vhost now carries the Let's Encrypt lines"
  else
    warn "certbot failed: the site stays on the self-signed certificate; re-run the script once DNS resolves"
  fi
fi

# ---------------------------------------------------------------------------
log "Drupal: $url"
# Installed = the database has tables, Drupal bootstraps on this site and the
# installer finished (install_time in state). Anything else with tables
# present is an error, never an install: an empty database is the only state
# that installs by itself, --reinstall the only way to install over tables.
install=0
if [ "$table_count" -eq 0 ]; then
  note "database is empty"
  install=1
else
  bootstrap="$(drush core:status --field=bootstrap 2> /dev/null || true)"
  install_time=""
  if [ "$bootstrap" = "Successful" ]; then
    install_time="$(drush state:get install_time 2> /dev/null || true)"
  fi
  if [ -n "$install_time" ]; then
    note "already installed"
  elif [ "$reinstall" -eq 1 ]; then
    note "database has $table_count tables but no finished install (bootstrap: ${bootstrap:-failed})"
  elif [ "$bootstrap" = "Successful" ]; then
    die "database $db_name has $table_count tables and Drupal bootstraps, but the install never finished (no install_time): fix it or pass --reinstall to drop it and install again"
  else
    die "database $db_name has $table_count tables but Drupal does not bootstrap on $url (broken settings? PHP fatal?): fix it, or pass --reinstall to drop it and install again"
  fi
  if [ "$reinstall" -eq 1 ]; then
    note "--reinstall: backup_db $domain 1, then the $table_count tables of $db_name are dropped and Drupal installed again"
    backup_db "$domain" 1 | tail -n 1
    install=1
  fi
fi
if [ "$install" -eq 1 ]; then
  note "installing profile $profile"
  # The installer appends the database credentials and a hash salt to
  # settings.php; both come from instance.env through settings.local.php, so
  # the committed file is put back afterwards.
  settings_copy="$(mktemp)"
  cp "$site_dir/settings.php" "$settings_copy"
  chmod u+w "$site_dir" "$site_dir/settings.php"
  install_args=(site:install "$profile" --site-name="$site_name" --site-mail="$site_mail" --account-name=admin --yes)
  if [ -n "$admin_pass" ]; then
    install_args+=(--account-pass="$admin_pass")
  else
    note "ADMIN_PASSWORD is empty in instance.env: drush generates one and prints it once below"
  fi
  drush "${install_args[@]}"
  if ! cmp -s "$settings_copy" "$site_dir/settings.php"; then
    cp "$settings_copy" "$site_dir/settings.php"
    note "settings.php restored to the committed file (the installer had written credentials into it)"
  fi
  rm -f "$settings_copy"
  chmod 640 "$site_dir/settings.php"
  chmod 750 "$site_dir"
fi

